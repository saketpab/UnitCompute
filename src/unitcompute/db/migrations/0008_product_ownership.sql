CREATE FUNCTION snapshot_requested_config() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.requested_config IS NULL THEN
  SELECT jsonb_build_object('name',d.name,'disk_gib',d.disk_gib,'instance_type',d.instance_type,'region',d.region) INTO NEW.requested_config FROM deployments d WHERE d.id=NEW.deployment_id;
