CREATE TABLE resources (
 id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
 user_id UUID NOT NULL,
 owner_id TEXT NOT NULL,
 chat_id UUID,
 deployment_id TEXT UNIQUE,
 name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 200),
 provider TEXT NOT NULL CHECK (provider IN ('aws','azure','gcp')),
 account_scope TEXT,
 region TEXT,
 native_type TEXT NOT NULL CHECK (length(native_type) BETWEEN 1 AND 200),
 provider_resource_id TEXT,
 execution_mechanism TEXT NOT NULL CHECK (execution_mechanism IN ('sdk','terraform','simulated','ansible')),
 os TEXT, cpu_count INTEGER CHECK (cpu_count > 0),
 memory_gb NUMERIC CHECK (memory_gb > 0), storage_gb INTEGER CHECK (storage_gb > 0),
 status TEXT NOT NULL CHECK (length(status) BETWEEN 1 AND 64),
 provider_config JSONB NOT NULL DEFAULT '{"schema_version":1,"kind":"compute","settings":{}}',
 approved_config JSONB, approved_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 sequence BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
 UNIQUE (id, owner_id),
 FOREIGN KEY (user_id, owner_id) REFERENCES users (id, owner_id),
 FOREIGN KEY (chat_id, owner_id) REFERENCES chat_sessions (uuid, owner_id),
 FOREIGN KEY (deployment_id, owner_id) REFERENCES deployments (id, owner_id),
 CHECK (provider_resource_id IS NULL OR account_scope IS NOT NULL),
 CHECK (jsonb_typeof(provider_config)='object' AND octet_length(provider_config::text)<=16384
 AND provider_config->>'schema_version'='1' AND jsonb_typeof(provider_config->'settings')='object'
 AND provider_config->>'kind' IN ('compute','network','storage','identity')
 AND provider_config - ARRAY['schema_version','kind','settings']='{}'::jsonb
 AND (provider_config->'settings') - ARRAY['name','disk_gib','instance_type','os','region','location','storage_class','network_cidr']='{}'::jsonb),
 CHECK (approved_config IS NULL OR (jsonb_typeof(approved_config)='object' AND octet_length(approved_config::text)<=16384
 AND approved_config - ARRAY['name','disk_gib','instance_type','region','config_hash','plan_id','plan_hash']='{}'::jsonb))
);
CREATE UNIQUE INDEX resources_native_identity ON resources (provider, account_scope, COALESCE(region,''), native_type, provider_resource_id) WHERE provider_resource_id IS NOT NULL;
CREATE INDEX resources_owner_page ON resources (owner_id, sequence DESC);
CREATE TABLE resource_relationships (
 owner_id TEXT NOT NULL REFERENCES users (owner_id),
 source_id UUID NOT NULL, target_id UUID NOT NULL,
 relationship TEXT NOT NULL CHECK (length(relationship) BETWEEN 1 AND 64),
 created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
 PRIMARY KEY (source_id, target_id, relationship), CHECK (source_id <> target_id),
 FOREIGN KEY (source_id, owner_id) REFERENCES resources (id, owner_id),
 FOREIGN KEY (target_id, owner_id) REFERENCES resources (id, owner_id)
);

CREATE FUNCTION sync_compute_resource() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE approved plans%ROWTYPE;
BEGIN
 SELECT * INTO approved FROM plans WHERE id=NEW.current_plan_id AND approved_at IS NOT NULL;
 INSERT INTO resources (id,user_id,owner_id,chat_id,deployment_id,name,provider,account_scope,region,native_type,provider_resource_id,execution_mechanism,os,cpu_count,memory_gb,storage_gb,status,provider_config,approved_config,approved_at,created_at,updated_at)
 SELECT NEW.uuid,u.id,NEW.owner_id,c.uuid,NEW.id,NEW.name,'aws',
 CASE WHEN NEW.provisioner='simulated' THEN 'simulation' ELSE approved.account_id END,
 NEW.region,'ec2:instance',NEW.instance_id,NEW.provisioner,'linux',2,1,NEW.disk_gib,NEW.status,
 jsonb_build_object('schema_version',1,'kind','compute','settings',jsonb_build_object('name',NEW.name,'disk_gib',NEW.disk_gib,'instance_type',NEW.instance_type,'region',NEW.region)),
 CASE WHEN approved.id IS NOT NULL THEN approved.requested_config || jsonb_build_object('config_hash',approved.config_hash,'plan_id',approved.id,'plan_hash',approved.plan_hash) END,
 approved.approved_at,NEW.created_at,NEW.updated_at
 FROM users u LEFT JOIN chat_sessions c ON c.id=NEW.chat_id AND c.owner_id=NEW.owner_id WHERE u.owner_id=NEW.owner_id
 ON CONFLICT (id) DO UPDATE SET name=EXCLUDED.name,chat_id=EXCLUDED.chat_id,
 account_scope=COALESCE(EXCLUDED.account_scope,resources.account_scope), provider_resource_id=EXCLUDED.provider_resource_id,
 storage_gb=EXCLUDED.storage_gb,status=EXCLUDED.status,provider_config=EXCLUDED.provider_config,
 approved_config=COALESCE(EXCLUDED.approved_config,resources.approved_config),
 approved_at=COALESCE(EXCLUDED.approved_at,resources.approved_at),updated_at=EXCLUDED.updated_at;
 RETURN NEW;
END $$;
CREATE TRIGGER deployments_resource AFTER INSERT OR UPDATE ON deployments FOR EACH ROW EXECUTE FUNCTION sync_compute_resource();
