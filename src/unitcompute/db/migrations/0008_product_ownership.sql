CREATE FUNCTION resolve_cloud_owner() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='UPDATE' AND NEW.cloud_owner_id IS DISTINCT FROM OLD.cloud_owner_id THEN
  RAISE EXCEPTION 'cloud ownership marker is immutable' USING ERRCODE='23514';
 END IF;
 IF NEW.cloud_owner_id IS NULL THEN NEW.cloud_owner_id=NEW.owner_id; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER deployment_cloud_owner BEFORE INSERT OR UPDATE ON deployments FOR EACH ROW EXECUTE FUNCTION resolve_cloud_owner();
