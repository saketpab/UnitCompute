-- An apply that failed, was interrupted or could not be verified may have changed AWS. It
-- leaves a durable obligation that is independent of Terraform state, tags or the known-ID
-- set. Evidence: 'captured' (what that apply stored was read and recorded), 'not_needed'
-- (the plan could not create resources), or 'uncaptured' (it could have, and nothing valid
-- was read). Only captured/not_needed obligations can ever be discharged, and only by a later
-- verified apply; 'uncaptured' blocks every plan and verified deletion for the deployment.
CREATE TABLE recovery_obligations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deployment_id TEXT NOT NULL REFERENCES deployments (id),
    job_id TEXT,
    plan_id TEXT,
    reason TEXT NOT NULL,
    evidence TEXT NOT NULL CHECK (evidence IN ('captured', 'not_needed', 'uncaptured')),
    created_at TIMESTAMPTZ NOT NULL,
    discharged_at TIMESTAMPTZ,
    discharged_by_job_id TEXT
);
CREATE INDEX recovery_obligations_open ON recovery_obligations (deployment_id, discharged_at);

CREATE OR REPLACE FUNCTION enforce_obligation_forward() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP = 'DELETE' THEN RAISE EXCEPTION 'recovery obligations cannot be deleted' USING ERRCODE='23514'; END IF;
 IF (to_jsonb(NEW) - ARRAY['evidence','discharged_at','discharged_by_job_id']) IS DISTINCT FROM
    (to_jsonb(OLD) - ARRAY['evidence','discharged_at','discharged_by_job_id']) OR OLD.discharged_at IS NOT NULL OR NOT (
   (OLD.evidence='uncaptured' AND (NEW.evidence='captured' ) AND NEW.discharged_at IS NULL AND NEW.discharged_by_job_id IS NOT DISTINCT FROM OLD.discharged_by_job_id)
   OR (OLD.evidence IN ('captured','not_needed') AND NEW.evidence=OLD.evidence AND NEW.discharged_at IS NOT NULL)
 ) THEN RAISE EXCEPTION 'recovery obligations only move forward' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER recovery_obligations_forward_only BEFORE UPDATE OR DELETE ON recovery_obligations FOR EACH ROW EXECUTE FUNCTION enforce_obligation_forward();
-- Backfill: every earlier failed apply. Unresolved ones (no later successful apply) start
-- 'uncaptured' so the worker must capture that apply's stored state before anything else;
-- resolved ones are recorded as discharged so their work directories can be pruned.
INSERT INTO recovery_obligations (deployment_id, job_id, plan_id, reason, evidence, created_at) SELECT p.deployment_id, j.id, p.id, 'legacy_unresolved_apply', 'uncaptured', p.created_at FROM plans p JOIN jobs j ON j.plan_id = p.id AND j.kind = 'apply' WHERE p.status = 'apply_failed' AND NOT EXISTS (SELECT 1 FROM jobs later WHERE later.deployment_id = p.deployment_id AND later.kind = 'apply' AND later.status = 'succeeded' AND later.sequence > j.sequence);
INSERT INTO recovery_obligations (deployment_id, job_id, plan_id, reason, evidence, created_at, discharged_at) SELECT p.deployment_id, j.id, p.id, 'legacy_resolved_apply', 'not_needed', p.created_at, p.created_at FROM plans p JOIN jobs j ON j.plan_id = p.id AND j.kind = 'apply' WHERE p.status = 'apply_failed' AND EXISTS (SELECT 1 FROM jobs later WHERE later.deployment_id = p.deployment_id AND later.kind = 'apply' AND later.status = 'succeeded' AND later.sequence > j.sequence);
